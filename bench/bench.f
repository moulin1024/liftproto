C     COMPILER-PARITY BENCHMARK: MANUAL UNROLL (LEGACY) VS PLAIN LOOP
      PROGRAM BENCH
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      PARAMETER (N=2000000, NREP=60)
      DIMENSION X(N),Y(N)
      INTEGER*8 C0,C1,CR
      DO 10 I=1,N
      X(I) = 1.0D0/DBLE(I)
      Y(I) = DBLE(MOD(I,7))-3.0D0
   10 CONTINUE
      S1 = 0.0D0
      S2 = 0.0D0
      CALL SYSTEM_CLOCK(C0,CR)
      DO 20 K=1,NREP
      S1 = S1 + DDOT(N,X,Y)
   20 CONTINUE
      CALL SYSTEM_CLOCK(C1)
      T1 = DBLE(C1-C0)/DBLE(CR)
      CALL SYSTEM_CLOCK(C0)
      DO 30 K=1,NREP
      S2 = S2 + DDOTP(N,X,Y)
   30 CONTINUE
      CALL SYSTEM_CLOCK(C1)
      T2 = DBLE(C1-C0)/DBLE(CR)
      CALL SYSTEM_CLOCK(C0)
      DO 40 K=1,NREP
      CALL DAXPY(N,1.0D-9,X,Y)
   40 CONTINUE
      CALL SYSTEM_CLOCK(C1)
      T3 = DBLE(C1-C0)/DBLE(CR)
      CALL SYSTEM_CLOCK(C0)
      DO 50 K=1,NREP
      CALL DAXPYP(N,1.0D-9,X,Y)
   50 CONTINUE
      CALL SYSTEM_CLOCK(C1)
      T4 = DBLE(C1-C0)/DBLE(CR)
      WRITE(*,100) T1,T2,T3,T4,S1.EQ.S2
  100 FORMAT(4F9.4,L3)
      END
